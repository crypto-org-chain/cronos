def _deploy_account(address, bytecode, storage):
    evm = {
        "address": address,
        "code": bytecode,
        "storage": storage,
    }
    auth = {
        "@type": "/ethermint.types.v1.EthAccount",
        "base_account": {
            "address": eth_to_bech32(address),
            "sequence": "1",
        },
        "code_hash": keccak(bytes.fromhex(bytecode)).hex(),
    }
    return evm, auth


def pool_genesis_account(reserve0: int, reserve1: int) -> (dict, dict):
    """Deploy ContentionPool with both reserves packed into slot 0."""
    slot0 = reserve0 | (reserve1 << 112)
    storage = [
        {
            "key": eth_abi.encode(["uint"], [0]).hex(),
            "value": eth_abi.encode(["uint"], [slot0]).hex(),
        }
    ]
    return _deploy_account(POOL_ADDRESS, POOL_BYTECODE, storage)


def nft_genesis_account() -> (dict, dict):
    """Deploy MintCounter; totalMinted/balanceOf default to zero, so no seeding."""
    return _deploy_account(NFT_ADDRESS, NFT_BYTECODE, [])
